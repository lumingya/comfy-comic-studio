"""Generate browser bridge constants and aliases to authoritative OpenAPI types."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "web/src/api/extensionProtocol.ts"
sys.path.insert(0, str(ROOT / "server"))

from mio_server.extensions.protocol import client_constants, contract_schemas  # noqa: E402

ALIASES = (
    "Manifest",
    "FloatingPosition",
    "PanelRequestSpec",
    "PanelContext",
    "PanelBridgeRequest",
    "PanelBridgeResponse",
    "PanelFromFrame",
    "PanelToFrame",
    "WorkspaceFromFrame",
    "WorkspaceToFrame",
    "WorkspaceKeyEvent",
    "SurfaceLifecycle",
    "EventDecision",
    "ThemeSettingsFromFrame",
    "ThemeSettingsToFrame",
    "ThemeSettingsSaved",
    "ThemeSettingsFailed",
)


def source() -> str:
    schemas = contract_schemas()
    aliases = []
    for name in ALIASES:
        key = f"MioContract_{name}"
        if key not in schemas:
            raise ValueError(f"missing exported protocol model: {name}")
        line = f"export type {name} = components['schemas']['{key}'];"
        aliases.append(
            line if len(line) <= 100 else f"export type {name} =\n  components['schemas']['{key}'];"
        )
    constants = typescript(client_constants())
    return (
        "// Generated by tools/generate_extension_contracts.py; do not edit.\n"
        "import type { components } from './schema';\n\n"
        f"export const BRIDGE = {constants} as const;\n\n" + "\n".join(aliases) + "\n"
    )


def typescript(value, level=0, column=0) -> str:
    """Emit the small JSON-compatible constants in the repository's TS house style."""
    padding = "  " * level
    inner = "  " * (level + 1)
    if isinstance(value, dict):
        return (
            "{\n"
            + "".join(
                f"{inner}{key}: {typescript(child, level + 1, len(inner) + len(key) + 2)},\n"
                for key, child in value.items()
            )
            + padding
            + "}"
        )
    if isinstance(value, list):
        if all(not isinstance(child, (dict, list)) for child in value):
            inline = "[" + ", ".join(typescript(child, level + 1) for child in value) + "]"
            if column + len(inline) <= 100:
                return inline
        return (
            "[\n"
            + "".join(f"{inner}{typescript(child, level + 1)},\n" for child in value)
            + padding
            + "]"
        )
    if isinstance(value, str):
        return "'" + json.dumps(value, ensure_ascii=False)[1:-1].replace("'", "\\'") + "'"
    return json.dumps(value)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    generated = source()
    if options.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != generated:
            print("extensionProtocol.ts is stale; run python tools/generate_extension_contracts.py")
            return 1
        print("extension bridge contracts up to date")
        return 0
    TARGET.write_text(generated, encoding="utf-8", newline="\n")
    print("wrote web/src/api/extensionProtocol.ts")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
